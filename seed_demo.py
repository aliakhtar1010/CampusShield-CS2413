
from db import get_connection, init_db

# All accounts and academic records are fictional.
USERS = [
    ("student01", "Amina Noor", "student"),
    ("student02", "Liam Chen", "student"),
    ("student03", "Sofia Patel", "student"),
    ("instructor01", "Dr. Morgan Lee", "instructor"),
    ("instructor02", "Dr. Priya Shah", "instructor"),
    ("security01", "Security Officer", "security_admin")
]

COURSES = [
    ("CS2413", "Information Security"),
    ("CS2383", "Data Structures and Algorithms")
]

# Only assigned instructors should eventually be
# permitted to modify grades for their courses.
INSTRUCTOR_ASSIGNMENTS = [
    ("instructor01", "CS2413"),
    ("instructor02", "CS2383")
]

# (Student, Course, Grade)
ACADEMIC_RECORDS = [
    ("student01", "CS2413", 88),
    ("student01", "CS2383", 94),
    ("student02", "CS2413", 73),
    ("student02", "CS2383", 86),
    ("student03", "CS2413", 91)
]


def seed_database():
    init_db()
    conn = get_connection()

    try:
        # Create accounts without usable credentials.
        # Abdullah will implement secure password
        # enrollment and activation in Phase 2.
        for username, name, role in USERS:
            conn.execute("""
                INSERT OR IGNORE INTO users
                (username, full_name, password_hash, role, is_active)
                VALUES (?, ?, ?, ?, 0)
            """, (username, name, "!NOT_ACTIVATED", role))

        # Insert courses.
        for code, title in COURSES:
            conn.execute("""
                INSERT OR IGNORE INTO courses (code, title)
                VALUES (?, ?)
            """, (code, title))

        # Retrieve IDs generated by SQLite.
        user_ids = {
            row["username"]: row["id"]
            for row in conn.execute(
                "SELECT id, username FROM users"
            )
        }

        course_ids = {
            row["code"]: row["id"]
            for row in conn.execute(
                "SELECT id, code FROM courses"
            )
        }

        # Assign instructors to their courses.
        for instructor, course in INSTRUCTOR_ASSIGNMENTS:
            conn.execute("""
                INSERT OR IGNORE INTO instructor_courses
                (instructor_id, course_id)
                VALUES (?, ?)
            """, (
                user_ids[instructor],
                course_ids[course]
            ))

        # Create enrollments and associated grades.
        for student, course, score in ACADEMIC_RECORDS:
            conn.execute("""
                INSERT OR IGNORE INTO enrollments
                (student_id, course_id)
                VALUES (?, ?)
            """, (
                user_ids[student],
                course_ids[course]
            ))

            enrollment = conn.execute("""
                SELECT id FROM enrollments
                WHERE student_id = ? AND course_id = ?
            """, (
                user_ids[student],
                course_ids[course]
            )).fetchone()

            conn.execute("""
                INSERT OR IGNORE INTO grades
                (enrollment_id, score)
                VALUES (?, ?)
            """, (enrollment["id"], score))

        conn.commit()

        print("\nCampusShield demo data initialized.")

        for table in [
            "users",
            "courses",
            "instructor_courses",
            "enrollments",
            "grades"
        ]:
            count = conn.execute(
                f"SELECT COUNT(*) FROM {table}"
            ).fetchone()[0]

            print(f"{table}: {count} records")

        print("\nAll demo accounts are inactive.")
        print("Authentication will be implemented separately.")

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


if __name__ == "__main__":
    seed_database()
